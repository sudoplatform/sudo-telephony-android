package com.sudoplatform.sudotelephony.internal.domain.entities.phoneNumber

import com.sudoplatform.sudotelephony.keys.KeyPair

/**
 * Request for [PhoneNumberService.provision].
 *
 * @property searchId [String] ID of the search the number came from.
 * @property phoneNumber [String] The number to provision, in E.164 format.
 * @property keyPair [KeyPair] The key pair whose public key the service registers to seal the
 *  number's messages.
 * @property ownershipProofToken [String] Proof that the caller owns the Sudo the number will
 *  belong to.
 * @property clientRefId [String] Client-supplied reference that makes the request idempotent.
 */
internal data class ProvisionPhoneNumberRequest(
    val searchId: String,
    val phoneNumber: String,
    val keyPair: KeyPair,
    val ownershipProofToken: String? = null,
    val clientRefId: String? = null,
)

/**
 * Input for [PhoneNumberService.list].
 *
 * @property limit [Int] Maximum number of items per page. When `null` the service applies
 *  its own default.
 * @property nextToken [String] A token generated by a previous call to allow for pagination.
 */
internal data class ListPhoneNumbersInput(
    val limit: Int? = null,
    val nextToken: String? = null,
)

/**
 * Output for [PhoneNumberService.list].
 *
 * @property items [List] The phone numbers retrieved on this page.
 * @property nextToken [String] A token to pass to the next call to get the next page.
 */
internal data class ListPhoneNumbersOutput(
    val items: List<PhoneNumberEntity>,
    val nextToken: String? = null,
)

/**
 * Domain service port for provisioned phone number operations.
 */
internal interface PhoneNumberService {
    /**
     * Provision a phone number from one of the caller's searches.
     *
     * @param request [ProvisionPhoneNumberRequest] The number to provision and the key to
     *  seal its messages with.
     * @return The [PhoneNumberEntity], which starts in
     *  [PhoneNumberStateEntity.PROVISIONING].
     */
    suspend fun provision(request: ProvisionPhoneNumberRequest): PhoneNumberEntity

    /**
     * Release one of the caller's phone numbers.
     *
     * @param id [String] ID of the phone number to release.
     * @return The [PhoneNumberEntity] in [PhoneNumberStateEntity.RELEASED].
     */
    suspend fun deprovision(id: String): PhoneNumberEntity

    /**
     * Retrieve one of the caller's phone numbers in any state.
     *
     * @param id [String] ID of the phone number to retrieve.
     * @return The [PhoneNumberEntity], or `null` when no number with [id] belongs to the
     *  caller.
     */
    suspend fun get(id: String): PhoneNumberEntity?

    /**
     * Retrieve a page of the caller's phone numbers.
     *
     * @param input [ListPhoneNumbersInput] Paging parameters.
     * @return A [ListPhoneNumbersOutput] holding the page and its next token.
     */
    suspend fun list(input: ListPhoneNumbersInput): ListPhoneNumbersOutput
}
